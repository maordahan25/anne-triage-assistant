"""
זיהוי הקשרי של דגל אדום לבבי — הבחנה בין "לחץ בחזה" ל"לחץ בעבודה".

הבעיה: בעברית "לחץ" הוא גם מתח נפשי וגם לחץ פיזי, ו"לב" מופיע גם
ב"הלב דופק מהר" של התקף חרדה. זיהוי לפי מילת מפתח בודדת מבלבל בין
תלונת חרדה לגיטימית לבין חשד לאירוע לבבי, ובפועל שער הבטיחות עצר
שיחות חרדה שלא היה צריך לעצור.

**כיוון התיקון הוא הוספת אבחנה, לא הסרת רגישות.** המודול הזה אינו
מבטל דגלים ואינו מרשה לאף גורם לבטל פסיקת חירום של Dr. Dexter; הוא
משמש בשני מקומות:
  1. הנחיית Dexter (crew/agents.py) — הכלל ההקשרי והדוגמאות השליליות.
  2. רשת ביטחון בקוד (crew/pipeline.py) — כשהתיאור *חד-משמעית* לבבי
     ו-Dexter בכל זאת לא פסק חירום, הקוד מעלה את הפסיקה. הכיוון היחיד
     שהרשת פועלת בו הוא להחמיר.

שתי חוקים, שניהם ברמת המשפט (כדי ש"לב דופק, ידיים מזיעות" ו"רק לחץ
גדול" — שני משפטים נפרדים — לא יצטרפו לדגל שאיש לא התכוון אליו):

  R1  ביטוי מפורש ("לחץ בחזה", "כבדות בחזה") **או** מילת כאב/לחץ
      במרחק של עד 3 מילים ממילת חזה/לב.
  R2  מילת כאב/לחץ יחד עם *הקרנה* לזרוע/ליד/ללסת/לכתף — הצירוף הקלאסי,
      גם כשהמילה "חזה" לא נאמרה.

הסף נקבע מדוגמאות אמיתיות: חלון של 3 מילים תופס "כואב לו חזק בחזה"
ו"לחץ על בית החזה", ואינו תופס "הלב שלי דופק והראש כואב" — שבו שתי
המילים באותו משפט אך אינן מתארות את אותו תסמין.
"""
from __future__ import annotations

import re

# ── אוצר המילים ─────────────────────────────────────────────────────────
# מילות כאב/לחץ פיזי. "לחוץ" אינו כאן בכוונה — זו מילת מתח נפשי.
PAIN_WORDS: tuple[str, ...] = (
    "כאב", "כאבים", "כואב", "כואבת", "כאבה", "לכאוב",
    "לחץ", "לוחץ", "לוחצת", "לחיצה",
    "מועקה", "מעיק", "מעיקה", "כבדות", "כבד",
    "צריבה", "צורב", "שורף", "שריפה", "הידוק", "חנק",
)

# מילות חזה/לב. הנרמול מסיר תחילית אחת (ה/ב/ל/ו/כ/ש) — ולכן "בחזה"
# ו"החזה" נתפסים, אבל "מחזה" (מילה אחרת לגמרי) לא: מ' אינה מוסרת.
CHEST_WORDS: tuple[str, ...] = (
    "חזה", "חזי", "חזהו", "חזית",     # "בית החזה" נתפס דרך "החזה"
    "לב", "ליבי", "לבי", "ליבו", "לבו", "ליבה",
)

# הקרנה — הפועל ויעד ההקרנה. שניהם נדרשים יחד (R2), אחרת "כאב ליד
# הברך" (מילת יחס, לא הקרנה) היה נספר.
RADIATION_VERBS: tuple[str, ...] = ("מקרין", "מקרינה", "מקרינים", "הקרנה",
                                    "פושט", "פושטת", "מתפשט", "מתפשטת")
RADIATION_TARGETS: tuple[str, ...] = ("יד", "ידיים", "זרוע", "הזרוע", "לסת",
                                      "הלסת", "כתף", "הכתף", "שכם")

# ביטויים מפורשים — נבדקים כמחרוזת, בלי תלות בחלון המילים.
EXPLICIT_PHRASES: tuple[str, ...] = (
    "לחץ בחזה", "לחץ בבית החזה", "לחץ על החזה", "לחץ בלב",
    "כאב בחזה", "כאבים בחזה", "כאב בבית החזה", "כאב בלב",
    "כואב בחזה", "כואב לי בחזה", "כואב לי החזה", "כואב לו בחזה",
    "מועקה בחזה", "מועקה בבית החזה", "כבדות בחזה", "לחיצה בחזה",
    "צריבה בחזה", "חנק בחזה", "הידוק בחזה", "לוחץ לי בחזה",
)

# שלילה מפורשת בלבד — צירופים שאין לגביהם ספק. הרשימה קצרה בכוונה:
# כל ניסוח שלילה שאינו כאן ייחשב כחיובי, וזה הכיוון הבטוח (עדיף
# להתריע על "לא הפסיק לכאוב לי בחזה" מאשר לפספס אותו).
NEGATION_PHRASES: tuple[str, ...] = (
    "אין לי כאב", "אין כאב", "אין לי כאבים", "אין כאבים",
    "אין לי לחץ", "אין לחץ", "אין מועקה", "אין לי מועקה",
    "לא כואב", "לא כואבת", "לא מרגיש כאב", "לא מרגישה כאב",
    "בלי כאב", "בלי כאבים", "ללא כאב", "ללא כאבים", "בלי לחץ",
    "ללא לחץ", "לא כאב", "שולל כאב", "נשלל כאב",
)

# דוגמאות שליליות מפורשות — "לחץ" במובן נפשי. אינן משמשות לחסימה
# (החוקים ממילא דורשים חזה/לב), אלא כאסמכתא בבדיקות ובהנחיה, וכדי
# שהרשימה תהיה במקום אחד גם לקוד וגם לפרומפט.
PSYCHOLOGICAL_PRESSURE_EXAMPLES: tuple[str, ...] = (
    "לחץ בעבודה", "לחוץ לפני ראיון", "מתח", "לחץ נפשי", "לחץ חברתי",
    "לחץ לפני מבחן", "תחושת לחץ", "לחץ של הלימודים",
)

MAX_WORD_DISTANCE = 3      # מרחק מילים מרבי בין מילת כאב למילת חזה/לב

_WORD = re.compile(r"[א-ת]+")
_SENTENCE_SPLIT = re.compile(r"[.!?;\n]|—| - ")
_PREFIXES = ("ה", "ב", "ל", "ו", "כ", "ש")


def _normalize(word: str) -> str:
    """הסרת תחילית אחת להשוואת מילה שלמה ('בחזה' -> 'חזה')."""
    if len(word) >= 3 and word[0] in _PREFIXES:
        return word[1:]
    return word


def _tokens(sentence: str) -> list[str]:
    return _WORD.findall(sentence)


def _indices(tokens: list[str], vocabulary: tuple[str, ...]) -> list[int]:
    """מיקומי המילים מהאוצר בתוך המשפט (מילה שלמה, אחרי נרמול תחילית)."""
    found = []
    for index, token in enumerate(tokens):
        if token in vocabulary or _normalize(token) in vocabulary:
            found.append(index)
    return found


def _is_negated(sentence: str) -> bool:
    return any(phrase in sentence for phrase in NEGATION_PHRASES)


def _sentence_has_cardiac_flag(sentence: str) -> bool:
    """האם *המשפט הזה* מתאר לחץ/כאב לבבי (R1 או R2)."""
    if _is_negated(sentence):
        return False
    if any(phrase in sentence for phrase in EXPLICIT_PHRASES):
        return True

    tokens = _tokens(sentence)
    pain = _indices(tokens, PAIN_WORDS)
    if not pain:
        return False

    # R1 — כאב/לחץ ליד מילת חזה/לב
    chest = _indices(tokens, CHEST_WORDS)
    if any(abs(p - c) <= MAX_WORD_DISTANCE for p in pain for c in chest):
        return True

    # R2 — כאב/לחץ + הקרנה לזרוע/ליד/ללסת/לכתף
    has_verb = any(verb in sentence for verb in RADIATION_VERBS)
    has_target = bool(_indices(tokens, RADIATION_TARGETS))
    return has_verb and has_target


def cardiac_red_flag(text: str) -> bool:
    """
    האם הטקסט מתאר, באופן חד-משמעי, לחץ/כאב בחזה או תמונה לבבית.

    בודק משפט-משפט: תלונת חרדה שבה "לב דופק" במשפט אחד ו"לחץ גדול"
    במשפט אחר לא מצטרפת לדגל שלא נאמר.
    """
    return any(
        _sentence_has_cardiac_flag(sentence)
        for sentence in _SENTENCE_SPLIT.split(text or "")
    )


def mentions_pressure_word(text: str) -> bool:
    """האם בכלל הוזכרה מילת לחץ/כאב (לאבחון ולבדיקות — לא לפסיקה)."""
    tokens = _tokens(text or "")
    return bool(_indices(tokens, PAIN_WORDS))
