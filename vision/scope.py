"""
גבול הסקופ — התמונה אינה מרחיבה את מה שאן מוסמכת לטפל בו.

אן מטפלת בארבעה תחומים בלבד: פצעים וחתכים · חרדה · התייבשות · הצטננות.
מודל הראייה, לעומת זאת, יתאר *כל* תמונה שיישלח אליו — שומה, פגיעה בעין,
פריחה לא מזוהה, ציפורן חודרנית. בלי הגבול הזה נוצרת בדיוק התקלה שהעיצוב
של אן קיים כדי למנוע: תיאור מרשים מהתמונה גורר ניסיון טיפול בנושא שאיש
לא אימן עליו את המערכת ושאין לו מקורות במאגר.

לכן: התיאור נסרק מול לקסיקון סגור של סימנים שמחוץ לתחום, ואם הוא נדלק —
ההקשר שמוזרק לסוכנים נושא הוראה מפורשת *לא לטפל*, אלא לומר שזה מחוץ
לתחום ולהמליץ על בדיקת רופא/ה. זו שכבת קוד, לא בקשה יפה בפרומפט.

הלקסיקון שמרני בכיוון אחד בכוונה: מילה שמופיעה גם בתחום מותר (למשל
"אדמומיות") אינה נכנסת אליו, כדי שתמונה לגיטימית של חתך לא תיפסל.
"""
from __future__ import annotations

import re

# סימנים שמחוץ לארבעת התחומים. כל ערך הוא ביטוי שמופיע בתיאור חזותי
# ולא באחד מהתחומים המותרים.
OUT_OF_SCOPE_MARKERS: tuple[str, ...] = (
    # נגעי עור שאינם פצע
    "שומה", "נקודת חן", "כתם לידה", "יבלת", "יבלות", "נגע פיגמנטי",
    "פריחה לא מזוהה", "נגע עורי", "גידול", "גוש בעור", "ציסטה",
    # עיניים
    "עין", "עיניים", "גלגל העין", "לחמית", "אישון", "עפעף",
    # פה ושיניים
    "שן", "שיניים", "חניכיים", "חלל הפה", "לשון",
    # ציפורניים ותחומים אחרים. "שיער" לבדו הושמט בכוונה: תיאור לגיטימי
    # של פצע עשוי להזכיר שיער סביבו, וזו הייתה חסימה מיותרת.
    "ציפורן", "ציפורניים", "פטרת", "קרקפת",
    # מצבים מערכתיים שאינם עזרה ראשונה ביתית
    "צהבת", "ורידים בולטים", "דליות",
)

# ביטויים שמעידים שהתמונה בכלל לא רלוונטית לתשאול רפואי.
NOT_A_BODY_MARKERS: tuple[str, ...] = (
    "אינה מציגה גוף", "לא מציגה גוף", "אין בתמונה גוף",
    "אינה מציגה חלק גוף", "לא נראה חלק גוף", "אינה תמונה של אדם",
)

_WORD = re.compile(r"[א-ת]+")

# תחיליות שמוסרות לפני ההשוואה, כדי ש"העין" יזוהה כ"עין". **מ' אינה
# ברשימה בכוונה**: היא הייתה הופכת את "מעין" (מילת יחס נפוצה) ל"עין"
# וחוסמת תיאור לגיטימי. גם י' אינה ברשימה — "ישן" אינו "שן".
_PREFIXES = ("ה", "ב", "ל", "ו", "כ", "ש")


def _tokens(text: str) -> set[str]:
    """
    טוקנים להשוואה: המילה כפי שהיא, ובנוסף הצורה בלי תחילית אחת. כך
    התאמת מילה-שלמה עובדת גם על "העין"/"בשן", בלי ליפול לתת-מחרוזות.
    """
    words = set(_WORD.findall(text or ""))
    stripped = {
        word[1:] for word in words
        if word[0] in _PREFIXES and len(word) >= 3
    }
    return words | stripped


def find_out_of_scope(description: str) -> list[str]:
    """
    הסימנים שמחוץ לתחום שנמצאו בתיאור (ריק = הכול בתחום).

    ביטוי רב-מילים נבדק כמחרוזת; מילה בודדת נבדקת כטוקן שלם, כדי
    ש"עין" לא תידלק בתוך "מעין" ו"שן" לא תידלק בתוך "ישן".
    """
    text = description or ""
    words = _tokens(text)
    found = []
    for marker in OUT_OF_SCOPE_MARKERS:
        hit = marker in text if " " in marker else marker in words
        if hit:
            found.append(marker)
    return found


def is_not_a_body_image(description: str) -> bool:
    """האם מודל הראייה אמר במפורש שאין בתמונה חלק גוף."""
    text = description or ""
    return any(marker in text for marker in NOT_A_BODY_MARKERS)


